package dev.denfry.promptcritical.sim.manufacturing;

/**
 * Межлистовая изоляция электротехнической стали (18 §18.6.8). {@code layerM} — толщина изолирующего слоя между
 * соседними пластинами, м. Без покрытия между пластинами остаётся окалина отжига ≈ 1 мкм [сверить]. Сериализуется по
 * {@code name()}: константы не переименовываются.
 */
public enum SheetCoating {
    NONE(1e-6),
    /** Бумажная прокладка между пластинами, как в машинах начала века: 30 мкм [сверить], толсто, но надёжно. */
    PAPER(30e-6),
    /** Фенольный лак, запечённый с двух сторон: 2 × 3 мкм [сверить: лаки С-3 по ASTM A976 — 1–5 мкм]. */
    PHENOLIC(6e-6);

    /** Изолирующий слой между пластинами, м. */
    public final double layerM;

    SheetCoating(double layerM) {
        this.layerM = layerM;
    }
}

package dev.denfry.promptcritical.sim.utilities;

/** Состояние ВРУ (08 §8.11). */
public enum AsuState {
    /** Компрессор стоит; блок может оставаться холодным. */
    OFF,
    /** Захолаживание: холод детандера идёт на массу блока, продукта нет. */
    COOLDOWN,
    RUNNING,
    /** Лёд CO₂/влаги в основном теплообменнике после проскока адсорберов: отогрев выше 0 °C. */
    ICED,
    /** Останов по углеводородам в LOX; сброс после слива LOX. */
    TRIPPED,
    /** Взрыв конденсатора-испарителя. */
    DESTROYED
}

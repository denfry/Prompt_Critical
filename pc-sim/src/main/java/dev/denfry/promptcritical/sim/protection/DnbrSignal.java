package dev.denfry.promptcritical.sim.protection;

/** Входы вычислителя DNBR (01 §1.11.4); у каждого вычислителя — свой комплект датчиков. */
public enum DnbrSignal {
    /** Давление в КД, Па. */
    PRESSURE,
    /** Температура холодной нитки, К. */
    INLET_TEMPERATURE,
    /** Расход через зону, доля номинала. */
    FLOW_FRAC,
    /** Мощность по камерам, доля номинала. */
    POWER_FRAC,
    /** Аксиальный коэффициент неравномерности F_z по внутризонным детекторам; NaN — детекторов нет. */
    AXIAL_PEAKING
}

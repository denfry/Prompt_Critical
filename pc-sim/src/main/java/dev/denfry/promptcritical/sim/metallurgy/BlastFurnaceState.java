package dev.denfry.promptcritical.sim.metallurgy;

/** Режим домны (08 §8.5.5). */
public enum BlastFurnaceState {
    COLD,
    /** Задувка: горн с коксом под дутьём, 2–5 сут физ. */
    BLOWING_IN,
    RUNNING,
    /** Тихий ход: дутьё &lt; 30 % дольше 1 ч физ.; горн остывает медленно. */
    BANKED,
    /** Подвисание: шихта не опускается. */
    HANGING,
    /** Осадка (один шаг SLOW): скачок давления, выброс через свечи. */
    SLIP,
    /** Закозление: холодный горн, выпуск невозможен; отогрев — дни физ. */
    CHILLED,
    /** Прорыв горна. */
    BURNTHROUGH
}

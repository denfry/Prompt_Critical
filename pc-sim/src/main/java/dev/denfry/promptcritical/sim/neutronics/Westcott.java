package dev.denfry.promptcritical.sim.neutronics;

/**
 * Не-1/v факторы Весткотта g(T_n) (01 §1.6.2): σ̂ = g σ₀ (√π/2)√(T₀/T_n). Приближённо по
 * C. H. Westcott, AECL-1101 (в изложении Lamarsh, табл. 3.2); значения Pu-241 и Pu-240 —
 * грубая оценка. GDD предполагает ресурс {@code westcott_g.json}; таблица мала и не настраивается,
 * поэтому живёт в коде. Главный игровой эффект — резонанс Pu-239 при 0,296 эВ: g_f растёт с T_n,
 * и TCM плутониевого топлива смещается в положительную сторону.
 */
public final class Westcott {
    public enum Factor { U235_A, U235_F, U238_A, PU239_A, PU239_F, PU240_A, PU241_A, PU241_F, XE135_A, SM149_A }

    /** Опорная температура 2200 м/с, К. */
    public static final double T0 = 293.6;
    private static final double[] T = {20, 100, 200, 400, 600, 800, 1000};
    private static final double[][] G = {
            {0.9780, 0.9610, 0.9457, 0.9294, 0.9229, 0.9182, 0.9118},
            {0.9759, 0.9581, 0.9411, 0.9208, 0.9108, 0.9036, 0.8956},
            {1.0017, 1.0031, 1.0049, 1.0085, 1.0122, 1.0159, 1.0198},
            {1.0723, 1.1611, 1.3388, 1.8905, 2.5321, 3.1006, 3.5353},
            {1.0487, 1.1150, 1.2528, 1.6904, 2.2037, 2.6595, 3.0079},
            {1.0220, 1.0558, 1.1030, 1.2069, 1.3226, 1.4473, 1.5793},
            {1.0400, 1.0790, 1.1340, 1.2610, 1.3880, 1.5000, 1.5950},
            {1.0430, 1.0840, 1.1430, 1.2760, 1.4070, 1.5230, 1.6200},
            {1.1581, 1.2103, 1.2360, 1.2208, 1.1634, 1.0960, 1.0333},
            {1.6170, 1.8874, 2.0903, 2.1854, 2.0852, 1.9246, 1.7568},
    };

    private Westcott() {}

    /** g при температуре нейтронного газа {@code tn}, К (линейно по таблице, края — константа). */
    public static double g(Factor f, double tn) {
        double t = tn - 273.15;
        double[] row = G[f.ordinal()];
        if (t <= T[0]) return row[0];
        for (int i = 1; i < T.length; i++) {
            if (t <= T[i]) return row[i - 1] + (row[i] - row[i - 1]) * (t - T[i - 1]) / (T[i] - T[i - 1]);
        }
        return row[row.length - 1];
    }

    /** Множитель максвелловского усреднения 1/v-сечения: (√π/2)√(T₀/T_n). */
    public static double oneOverV(double tn) {
        return 0.5 * Math.sqrt(Math.PI) * Math.sqrt(T0 / tn);
    }
}

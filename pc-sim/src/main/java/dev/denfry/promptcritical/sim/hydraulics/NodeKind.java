package dev.denfry.promptcritical.sim.hydraulics;

/** Модель узла гидросети (01 §1.2.1). */
public enum NodeKind {
    /** Гомогенная равновесная смесь, одна пара (M, U). */
    HEM,
    /** Равновесная термодинамика + уровень смеси и фазовый отбор (§1.2.5, §1.3.6). */
    SEPARATED,
    /** Две подсистемы с общим давлением и релаксацией (§1.3.8). Решателем пока не поддерживается. */
    TWO_REGION,
    /** Идеальная смесь газов с пулом жидкости (§1.3.10). Решателем пока не поддерживается. */
    GAS_MIXTURE,
    /** Заданные p(t), h(t); бесконечная ёмкость. */
    BOUNDARY
}

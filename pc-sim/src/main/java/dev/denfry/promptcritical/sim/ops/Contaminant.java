package dev.denfry.promptcritical.sim.ops;

/**
 * Вредная примесь вдыхаемого воздуха по группам противогазовых фильтров (13 §13.7, EN 14387 / ГОСТ 12.4.235).
 * {@link #ASPHYXIANT} — простые удушающие газы (N₂, Ar, CO₂, CH₄): их не задерживает ни один фильтр, они вытесняют
 * кислород.
 */
public enum Contaminant {
    /** Органические пары с температурой кипения выше 65 °C (бензол, бензин): фильтр A. */
    ORGANIC_VAPOUR,
    /** Низкокипящие органические (≤ 65 °C: диметиловый эфир, метанол): фильтр AX. */
    LOW_BOILING_ORGANIC,
    /** Неорганические газы (хлор, сероводород, HCN): фильтр B. */
    INORGANIC_GAS,
    /** Кислые газы (SO₂, HCl, HF): фильтр E. */
    ACID_GAS,
    /** Аммиак и амины: фильтр K. */
    AMMONIA,
    /** Угарный газ: гопкалит (фильтр CO). */
    CARBON_MONOXIDE,
    /** Пыль, зола, сажа, аэрозоли (в том числе радиоактивные): противоаэрозольный фильтр P. */
    PARTICLES,
    /** Простой удушающий газ: защищает только изолирующий аппарат. */
    ASPHYXIANT
}

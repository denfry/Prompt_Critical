package dev.denfry.promptcritical.sim.waste;

/**
 * Химический элемент радионуклида с точки зрения миграции: коэффициент распределения K_d (сорбция на породе) и
 * коэффициент накопления в пресноводной рыбе. Значения — округлённые геометрические средние IAEA TRS-472 (2010,
 * «Handbook of Parameter Values for the Prediction of Radionuclide Transfer in Terrestrial and Freshwater
 * Environments»): K_d для песчаных и глинистых грунтов, CR рыбы — L/kg сырой массы. Разброс в первоисточнике —
 * порядок величины в обе стороны, поэтому здесь важен порядок: цезий и плутоний держатся на породе тысячи лет, иод,
 * технеций и углерод-14 идут почти со скоростью воды.
 *
 * <p>Короткоживущие элементы (Y, Zr, Nb, Ru, Ir, N) за время миграции распадаются при любом K_d, им даны порядки по
 * аналогии. Криптон — инертный газ: в грунтовой воде не задерживается, но и в питьевую воду не переходит (доза 0).
 * C-14 в рыбе — модель удельной активности: углерод рыбы (≈ 0,11 кг/кг) к растворённому неорганическому углероду
 * воды (≈ 2·10⁻⁵ кг/л) даёт CR ≈ 5000 л/кг.
 */
public enum Element {
    CO(60, 1000, 100), NI(60, 650, 20), C(1, 1, 5000), SR(22, 110, 30), Y(100, 1000, 10), ZR(600, 2000, 10),
    NB(160, 1000, 10), RU(50, 400, 10), TC(0.1, 0.2, 20), I(1, 7, 40), CS(530, 5500, 2000), KR(0, 0, 0), IR(100, 1000, 10),
    N(0, 0, 0), PU(400, 2000, 30), AM(2000, 5000, 30), NP(5, 55, 30);

    /** K_d в песке и в глине, м³/кг. */
    public final double kdSandM3Kg, kdClayM3Kg;
    /** Коэффициент накопления в рыбе: Бк/кг рыбы на Бк/м³ воды, м³/кг. */
    public final double fishM3Kg;

    Element(double kdSandLKg, double kdClayLKg, double fishLKg) {
        this.kdSandM3Kg = kdSandLKg / 1000;
        this.kdClayM3Kg = kdClayLKg / 1000;
        this.fishM3Kg = fishLKg / 1000;
    }
}

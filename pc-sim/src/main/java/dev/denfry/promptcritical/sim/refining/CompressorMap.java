package dev.denfry.promptcritical.sim.refining;

/**
 * Паспортная линия помпажа компрессора в приведённых координатах (03d §3d.5.12, контракт 03d §3d.16 «09: компрессор и
 * компаундирование»): q²_r = Δp_o/p_s (перепад на диафрагме всаса к давлению всаса) на границе устойчивой работы при
 * степени сжатия R_c = p_d/p_s. Координаты инвариантны к составу и температуре газа, поэтому одна линия годится на
 * все режимы — из неё антипомпажный регулятор {@code PC_ANTISURGE} считает запас S_s = q²_surge(R_c)/q²_r.
 */
public interface CompressorMap {
    /** q²_r линии помпажа при степени сжатия {@code pressureRatio}, в единицах Δp_o/p_s паспорта. */
    double surgeQ2(double pressureRatio);
}

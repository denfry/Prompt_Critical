package dev.denfry.promptcritical.sim.automation;

/** Режим реле времени (03d §3d.3.4): как функциональные блоки МЭК 61131-3 (§3d.5.11). */
public enum TimeRelayMode {
    /** TON: выдержка на включение. */
    ON_DELAY,
    /** TOF: выдержка на отключение. */
    OFF_DELAY,
    /** TP: импульс заданной длительности по фронту, без перезапуска. */
    PULSE,
    /** Симметричный генератор импульсов, пока катушка под напряжением. */
    FLASHER
}

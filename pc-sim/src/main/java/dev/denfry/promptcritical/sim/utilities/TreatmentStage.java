package dev.denfry.promptcritical.sim.utilities;

/** Ступени водоподготовки (08 §8.12) в порядке потока; выключенная ступень пропускает воду как есть. */
public enum TreatmentStage {
    INLET,
    /** Осветлитель: коагуляция и известкование. */
    CLARIFIER,
    SAND_FILTER,
    /** Катионитные колонны: H- и Na-группы параллельно, смешение после них. */
    CATION,
    /** Декарбонизатор: отдувка CO₂ воздухом (вода снова насыщается кислородом). */
    DECARBONIZER,
    DEAERATOR,
    /** Коррекционная обработка: NH₃ до pH 9,1, N₂H₄ — остаток O₂. */
    DOSING
}

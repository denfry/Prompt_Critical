package dev.denfry.promptcritical.sim.mechanics;

/** Муфта между валом Create и машиной (03a §3a.2.2): задаёт нижнюю границу момента привода τ_min. */
public enum CouplingType {
    /** Обгонная: τ_min = 0, привод только «толкает», при ω &gt; ω_cmd машина выбегает свободно (по умолчанию, R2). */
    FREEWHEEL,
    /** Фрикционная: τ_min = −τ_max при включённой муфте, 0 при выключенной; торможение рассеивается в муфте. */
    FRICTION_CLUTCH,
    /** Жёсткая (самотормозящая червячная передача): τ_min = −τ_max; только приводы СУЗ. */
    RIGID
}

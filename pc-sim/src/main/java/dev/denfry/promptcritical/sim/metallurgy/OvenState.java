package dev.denfry.promptcritical.sim.metallurgy;

/** Состояние камеры коксовой батареи (08 §8.4.1). */
public enum OvenState {
    EMPTY,
    /** Загрузка; масса ещё меньше проектной. */
    CHARGING,
    COKING,
    /** Коксование закончено, центр ≥ 950 °C; передержка &gt; 2 ч физ. — пережог. */
    READY,
    /** Выталкивали раньше срока: недококс прилип, поршень перегружен; ждёт, пока дококсуется. */
    STICKER
}

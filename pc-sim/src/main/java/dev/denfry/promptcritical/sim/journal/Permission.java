package dev.denfry.promptcritical.sim.journal;

/** Разрешение на станции (04d §4d.9.2): строка матрицы прав; «минимальная роль» в 03b — роль, содержащая разрешение. */
public enum Permission {
    /** Чтение приборов, вход на станцию. */
    READ,
    /** Управление механизмами реакторной и турбинной части. */
    CONTROL,
    /** Квитирование сигнализации. */
    ACK_ALARM,
    /** Сброс АЗ, шельфинг, перевод на РЩУ, байпас-ключ. */
    PROTECTION,
    /** Испытания (опробование АЗ, падение стержней, герметичность), настройка устройств, {@code defineAlarm}. */
    TESTS_AND_SETUP,
    /** Химпередел, каскад. */
    CHEMISTRY,
    /** Пределы радиационных мониторов, допуск в зоны (04b). */
    RADIATION_LIMITS,
    /** Перевод в {@code MAINTENANCE}, ремонт, поверка, замена подшипников. */
    MAINTENANCE,
    /** Ломание и установка блоков станции. */
    BREAK_PLACE,
    /** Выпуск и отзыв ключ-карт, выдача ролей. */
    MANAGE_ROLES,
    /** Спот-сделки на бирже, продажа энергии, квоты CO₂ (14). */
    SPOT_TRADE,
    /** Контракты с депозитом и неустойкой (14). */
    CONTRACTS
}
